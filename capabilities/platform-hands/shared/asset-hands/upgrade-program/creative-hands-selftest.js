'use strict';
const assert=require('assert');
const Hands=require('./creative-hands');
const R=require('./precision-raster');
const P=require('./creative-precision');

const rgba=Buffer.alloc(8*8*4);
for(let y=0;y<8;y+=1)for(let x=0;x<8;x+=1){const i=(y*8+x)*4;rgba[i]=x*30;rgba[i+1]=y*30;rgba[i+2]=80;rgba[i+3]=255;}
const image=R.image({width:8,height:8,rgba});
const audit=Hands.audit();
assert.equal(audit.total,144);
assert.equal(audit.counts.EXECUTABLE,144);
assert.equal(audit.by_family.brush,12);
assert.equal(audit.by_family.adjust,17);
assert.equal(audit.by_family.vector,9);
assert.equal(audit.by_family.selection,18);
assert.equal(audit.by_family.transform,5);
assert.equal(audit.by_family['vector-core'],6);
assert.equal(audit.by_family.graph,1);
assert.deepEqual(Hands.get('creative.filter.box-blur').limits.radius,{min:1,max:7});
assert.throws(()=>Hands.invoke('creative.filter.box-blur',{image,spec:{radius:8}}),/radius outside 1\.\.7/);

const bright=Hands.invoke('creative.adjust.brightness',{image,spec:{amount:.2}});
assert.equal(bright.status,'EXECUTED');
assert.notEqual(bright.result.digest,image.digest);
const blur=Hands.invoke('creative.filter.gaussian-blur',{image,spec:{radius:1,sigma:1}});
assert.equal(blur.status,'EXECUTED');
assert.notEqual(blur.result.digest,image.digest);
const brush={id:'proof',samples:[{x:1,y:2,pressure:1,time_ms:0},{x:7,y:2,pressure:1,time_ms:10}],size:2,spacing:.5,hardness:1,opacity:1,flow:1};
const paint=Hands.invoke('creative.brush.paint',{image,brush,spec:{colour_rgba:[255,0,0,255]}});
assert.equal(paint.result.receipt.status,'PASS');
assert(paint.result.receipt.changed_pixels>0);
const erase=Hands.invoke('creative.brush.erase',{image,brush});
assert.equal(erase.result.receipt.status,'PASS');
const selection=P.shapeMask({width:8,height:8,kind:'rectangle',x:2,y:2,rect_width:3,rect_height:3});
const clone=Hands.invoke('creative.retouch.clone',{image,mask:selection,spec:{source_offset:{x:-2,y:0}}});
assert.equal(clone.status,'EXECUTED');
const wand=Hands.invoke('creative.selection.magic-wand',{image,spec:{x:0,y:0,tolerance:0,connectivity:4}});
assert.equal(wand.result.schema,'axm.precision-mask/v1');
const homography=Hands.invoke('creative.transform.homography',{source:[{x:0,y:0},{x:8,y:0},{x:8,y:8},{x:0,y:8}],destination:[{x:0,y:0},{x:8,y:0},{x:7,y:8},{x:1,y:8}]});
assert.equal(homography.result.kind,'homography');
const offset=Hands.invoke('creative.vector-core.offset-polyline',{points:[{x:0,y:0},{x:5,y:0},{x:5,y:5}],distance:1,id:'offset',closed:false});
assert.equal(offset.result.schema,'axm.precision-vector-path/v1');
const graph=Hands.invoke('creative.graph.compile',{graph:{id:'g',nodes:[{id:'a',op:'source'},{id:'b',op:'invert',inputs:['a']}],outputs:['b']}});
assert.deepEqual(graph.result.order,['a','b']);
const star=Hands.invoke('creative.vector.star',{spec:{id:'star',points:5,cx:10,cy:10,outer_radius:8,inner_radius:3}});
assert.equal(star.result.schema,'axm.precision-vector-path/v1');
const quant=Hands.invoke('creative.pixel.palette-quantize',{image,palette:[[0,0,0],[255,255,255],[255,0,0],[0,0,255]]});
assert.equal(quant.result.image.schema,'axm.precision-raster/v1');
const sheet=Hands.invoke('creative.pixel.spritesheet',{frames:[image,image],spec:{columns:2,padding:1}});
assert.equal(sheet.result.frames,2);
assert.equal(sheet.result.image.width,17);
console.log(JSON.stringify({status:'PASS',executable_hands:audit.total,by_family:audit.by_family,bright:bright.digest,paint:paint.digest,wand:wand.digest,homography:homography.digest,offset:offset.digest,graph:graph.digest,star:star.digest,sheet:sheet.digest},null,2));
